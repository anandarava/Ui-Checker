#!/usr/bin/env node
// Builds the fixture pages from fixtures/src/*.template.html.
//
//   node scripts/build-fixtures.mjs          write fixtures/<name>-defects.html and <name>-clean.html
//   node scripts/build-fixtures.mjs --check  fail when the files on disk are out of date
//
// One template gives two pages that differ ONLY by the seeded defects, so a
// finding on the clean page is always a false positive and a missed defect on
// the defects page is always a miss.
//
// Template syntax
//   {{#D3}}text for the defects page{{else}}text for the clean page{{/D3}}
//   {{#D3}}text for the defects page only{{/D3}}
//   {{VARIANT}}   "defects" or "clean"
//
// Every template carries its defect list:
//   <script type="application/json" id="expected">[ { "id": "D3", "rule": "LAY-06", "target": "holiday-grid", "note": "..." } ]</script>
//
//   id      the {{#D..}} block that plants the defect
//   rule    rule id of the catalogue, or null for a Phase 5 page-wide check
//   target  value of the data-fx attribute on the element the finding must point at
//   review  true: belongs on the "Needs review" tab, not a definite finding
//   both    true: present in the clean page too (an intentional difference the tool should only list for review)
//   via     id of another defect that plants this one (it has no block of its own)
//
// The clean page keeps only the entries marked "both". The data-fx attributes
// exist for the tests; the scan engine must never read them.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "fixtures", "src");
const OUT = path.join(ROOT, "fixtures");
const RULES = new Set(JSON.parse(readFileSync(path.join(ROOT, "shared", "ui-rules.json"), "utf8")).rules.map((r) => r.id));

const BLOCK_RE = /\{\{#(D\d+)\}\}([\s\S]*?)\{\{\/\1\}\}/g;
const MANIFEST_RE = /(<script type="application\/json" id="expected">)([\s\S]*?)(<\/script>)/;

export function render(template, variant) {
  const defects = variant === "defects";
  let html = template.replace(BLOCK_RE, (_all, _id, body) => {
    const [whenDefect, whenClean = ""] = body.split("{{else}}");
    return defects ? whenDefect : whenClean;
  });
  html = html.replaceAll("{{VARIANT}}", variant);
  const leftover = html.match(/\{\{[#/]?[A-Za-z0-9]+\}\}/);
  if (leftover) throw new Error(`unresolved template tag ${leftover[0]}`);
  return html.replace(MANIFEST_RE, (_all, open, json, close) => {
    const entries = JSON.parse(json);
    const kept = defects ? entries : entries.filter((e) => e.both === true);
    return `${open}${JSON.stringify(kept, null, 2)}${close}`;
  });
}

/** Checks a template's defect list against its blocks and its data-fx targets. Returns the entries. */
export function validate(name, template) {
  const match = template.match(MANIFEST_RE);
  if (!match) throw new Error(`${name}: no <script type="application/json" id="expected"> manifest`);
  const entries = JSON.parse(match[2]);
  const blocks = new Set([...template.matchAll(BLOCK_RE)].map((m) => m[1]));
  const ids = new Set();
  const defectsHtml = render(template, "defects");
  for (const e of entries) {
    if (ids.has(e.id)) throw new Error(`${name}: defect ${e.id} is listed twice`);
    ids.add(e.id);
    if (e.rule !== null && !RULES.has(e.rule)) throw new Error(`${name}: defect ${e.id} names unknown rule ${e.rule}`);
    if (!e.both && !blocks.has(e.id) && !(e.via && blocks.has(e.via))) throw new Error(`${name}: defect ${e.id} has no {{#${e.id}}} block`);
    if (!defectsHtml.includes(`data-fx="${e.target}"`)) throw new Error(`${name}: defect ${e.id} targets data-fx="${e.target}", which is not in the page`);
  }
  for (const id of blocks) if (!ids.has(id)) throw new Error(`${name}: block {{#${id}}} is not in the defect list`);
  return entries;
}

function indexPage(pages) {
  const rows = pages
    .map((p) => `      <tr><td>${p.name}</td><td><a href="${p.name}-defects.html">defects</a> (${p.count})</td><td><a href="${p.name}-clean.html">clean</a></td></tr>`)
    .join("\n");
  return `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8">
    <title>UI Consistency Checker fixtures</title>
    <style>
      body { font-family: system-ui, sans-serif; margin: 32px; color: #111; }
      table { border-collapse: collapse; }
      th, td { text-align: left; padding: 6px 16px 6px 0; border-bottom: 1px solid #ddd; }
    </style>
  </head>
  <body>
    <h1>Fixtures</h1>
    <p>Generated by <code>npm run fixtures:build</code> from <code>fixtures/src</code>. Do not edit the generated pages.</p>
    <table>
      <thead><tr><th>Page</th><th>With seeded defects</th><th>Clean</th></tr></thead>
      <tbody>
${rows}
      </tbody>
    </table>
  </body>
</html>
`;
}

export function buildAll() {
  const files = {};
  const pages = [];
  for (const file of readdirSync(SRC).filter((f) => f.endsWith(".template.html")).sort()) {
    const name = file.replace(/\.template\.html$/, "");
    const template = readFileSync(path.join(SRC, file), "utf8").replace(/\r\n/g, "\n");
    const entries = validate(name, template);
    files[`${name}-defects.html`] = render(template, "defects");
    files[`${name}-clean.html`] = render(template, "clean");
    pages.push({ name, count: entries.filter((e) => !e.both).length });
  }
  files["index.html"] = indexPage(pages);
  return files;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const check = process.argv.includes("--check");
  const files = buildAll();
  const stale = [];
  mkdirSync(OUT, { recursive: true });
  for (const [name, content] of Object.entries(files)) {
    const target = path.join(OUT, name);
    const current = existsSync(target) ? readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
    if (current === content) continue;
    if (check) stale.push(name);
    else writeFileSync(target, content);
  }
  if (check && stale.length > 0) {
    console.error(`Out of date: ${stale.join(", ")}. Run "npm run fixtures:build".`);
    process.exit(1);
  }
  console.log(check ? "Fixtures are up to date." : `${Object.keys(files).length} fixture files written to fixtures/`);
}
